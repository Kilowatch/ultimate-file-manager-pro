/**
 * Open Source Licenses screen.
 *
 * Reads the licenses.json file generated by the cashapp/licensee Gradle plugin
 * (placed in res/raw/ during build) and displays each library's name, version,
 * and SPDX license identifier in a scrollable list.
 *
 * Falls back to a curated static list if the generated JSON is not yet present
 * (e.g. first-run after a clean in development).
 */
