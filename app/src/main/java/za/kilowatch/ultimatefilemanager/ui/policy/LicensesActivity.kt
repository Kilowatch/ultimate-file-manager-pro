            ))
        } else {
            libraries.forEach { lib ->
                content.addView(makeLibraryCard(lib))
            }
        }

        scroll.addView(content)
        root.addView(header)
        root.addView(scroll)

        setContentView(root)

        ViewCompat.setOnApplyWindowInsetsListener(root) { v, insets ->
            val bars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            v.setPadding(bars.left, bars.top, bars.right, bars.bottom)
            insets
        }
    }

    // ── Data loading ──────────────────────────────────────────────────────────

    private data class LibInfo(val name: String, val version: String, val license: String, val url: String)

    private fun loadLibraries(): List<LibInfo> {
        return try {
            val rawId = resources.getIdentifier("licenses", "raw", packageName)
            if (rawId == 0) return staticFallback()
            val json = resources.openRawResource(rawId).bufferedReader().readText()
            val arr = JSONArray(json)
            val list = (0 until arr.length()).map { i ->
                val obj = arr.getJSONObject(i)
                val name = obj.optString("name").ifBlank { obj.optString("groupId") + ":" + obj.optString("artifactId") }
                val version = obj.optString("version", "")
                val spdx = obj.optJSONArray("spdxLicenses")?.let { spdxArr ->
                    (0 until spdxArr.length()).joinToString(", ") { j ->
                        spdxArr.getJSONObject(j).optString("identifier", "")
                    }
                } ?: obj.optJSONArray("unknownLicenses")?.let { ul ->
                    (0 until ul.length()).joinToString(", ") { j ->
                        ul.getJSONObject(j).optString("name", "Unknown")
                    }
                } ?: getString(R.string.see_project_page)
                val url = obj.optString("scm", "").ifBlank {
                    obj.optJSONArray("spdxLicenses")?.optJSONObject(0)?.optString("url", "") ?: ""
                }
                LibInfo(name, version, spdx, url)
            }.toMutableList()

            if (list.none { it.name.contains("rclone", ignoreCase = true) }) {
                list.add(LibInfo(getString(R.string.add_online_storage_rclone), "1.75.0", "MIT", "https://github.com/rclone/rclone"))
            }
            if (list.none { it.name.contains("ffmpeg", ignoreCase = true) }) {
                list.add(LibInfo(getString(R.string.ffmpeg_lgpl_build), "8.1.2", "LGPL-2.1", "https://ffmpeg.org"))
            }
            if (list.none { it.name.contains("shizuku", ignoreCase = true) || it.name.contains("shevery", ignoreCase = true) }) {
                list.add(LibInfo("Shizuku & Shevery API (dev.rikka.shizuku:api)", "13.1.5", "Apache-2.0", "https://github.com/HmnDev-Tech/shevery"))
            }

            list.sortedBy { it.name.lowercase() }
        } catch (e: Exception) {
            staticFallback()
        }
    }

